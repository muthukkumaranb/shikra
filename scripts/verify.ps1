<#
.SYNOPSIS
One-line verification script for Windows environments without GNU make.

.DESCRIPTION
Executes the four verification steps matching 'make verify':
1. Pytest suite (excluding raw NASA data tests)
2. Full simulation reproduction pipeline
3. Bitwise artifact equality check against committed results
4. Git working tree diff validation (excluding platform-variable PNG figures)

Exits non-zero immediately if any step fails.
#>
param(
    [string]$Py = ".venv\Scripts\python.exe"
)

$ErrorActionPreference = "Stop"

if (-not (Test-Path $Py)) {
    if (Get-Command python -ErrorAction SilentlyContinue) {
        $Py = "python"
    } else {
        Write-Error "Python executable not found at '$Py' and 'python' not on PATH."
        exit 1
    }
}

Write-Output "== Step 1/4: Running pytest =="
& $Py -m pytest -q -m "not data"
if ($LASTEXITCODE -ne 0) {
    Write-Error "pytest failed with exit code $LASTEXITCODE"
    exit $LASTEXITCODE
}

Write-Output "== Step 2/4: Reproducing fleet simulations and summary artifacts =="
if (Get-Command make -ErrorAction SilentlyContinue) {
    make reproduce-sim PY=$Py
    if ($LASTEXITCODE -ne 0) {
        Write-Error "make reproduce-sim failed with exit code $LASTEXITCODE"
        exit $LASTEXITCODE
    }
} else {
    Write-Output "--- sim.runner ---"
    & $Py -m shikra.sim.runner
    if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }

    Write-Output "--- summary.py ---"
    & $Py scripts/summary.py
    if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }

    Write-Output "--- heatmap.py ---"
    & $Py scripts/heatmap.py
    if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }

    Write-Output "--- bias.py ---"
    & $Py scripts/bias.py
    if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }

    Write-Output "--- supply_shock.py ---"
    & $Py scripts/supply_shock.py
    if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }

    Write-Output "--- figures.py ---"
    & $Py scripts/figures.py
    if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }

    Write-Output "--- readme_table.py ---"
    & $Py scripts/readme_table.py
    if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }
}

Write-Output "== Step 3/4: Checking byte-level reproduction against committed results =="
& $Py scripts/check_reproduce.py
if ($LASTEXITCODE -ne 0) {
    Write-Error "check_reproduce.py failed with exit code $LASTEXITCODE"
    exit $LASTEXITCODE
}

Write-Output "== Step 4/4: Validating clean working tree for results CSVs =="
# Note: PNGs are excluded because platform-specific font/matplotlib rasterization varies across OSes.
git diff --exit-code --stat -- results/ ':!results/*.png'
if ($LASTEXITCODE -ne 0) {
    Write-Error "git diff detected unexpected modifications in results/"
    exit $LASTEXITCODE
}

Write-Output "VERIFIED: tests pass, every committed result regenerated byte-identical."
