"""Theme guard-rails: no network URLs in the app tree, no mock-up content,
and every page loads the shared theme."""

from __future__ import annotations

import re
import subprocess
from pathlib import Path

import pytest

ROOT = Path(__file__).parent.parent
APP = ROOT / "app"
PAGES = [APP / "Home.py", *sorted((APP / "pages").glob("*.py"))]

URL_RE = re.compile(rb"https?://", re.IGNORECASE)

# Substrings (case-insensitive) that must not appear in any tracked app file.
FORBIDDEN_SUBSTRINGS = [
    # numbers from the design mock-ups
    "75.9%", "41/54", "41 / 54", "+4.8", "91.4%", "68.2%", "3.2/yr", "3.2 / yr", "15.2 A/C",
    # forecast framing that is not shown
    "sortie probability", "probability of meeting", "p(meet)", "readiness-at-risk",
    # invented people, units and identifiers
    "maj.", "capt.", "wing 42", "#042", "v4.2",
    # wording
    "ops room", "readiness-backward", "tamper-proof", "blockchain", "certified",
    "compliant", "command directive", "tactical", "ground truth rul", "ground-truth rul",
]
# Whole words (case-insensitive), so e.g. "alphabet" does not trip "alpha".
FORBIDDEN_WORDS = ["vance", "chen", "hawks", "cobras", "falcons", "alpha", "zulu", "nsn"]
TEXT_SUFFIXES = {".py", ".css", ".svg", ".txt", ".md", ".toml", ".json", ".html", ".yaml", ".yml"}


def _app_source_files() -> list[Path]:
    """Every file under app/ except generated bytecode caches."""
    return [p for p in APP.rglob("*") if p.is_file() and "__pycache__" not in p.parts]


def _tracked_app_text_files() -> list[Path]:
    out = subprocess.run(
        ["git", "ls-files", "app"], cwd=ROOT, capture_output=True, text=True, check=True
    ).stdout.split()
    return [ROOT / p for p in out if Path(p).suffix.lower() in TEXT_SUFFIXES]


def test_theme_css_has_no_urls():
    css = APP / "assets" / "theme.css"
    assert css.exists()
    assert not URL_RE.search(css.read_bytes())


def test_no_urls_anywhere_in_app():
    files = _app_source_files()
    assert files
    hits = [str(p.relative_to(ROOT)) for p in files if URL_RE.search(p.read_bytes())]
    assert hits == [], f"web URLs found in: {hits}"


def test_tracked_app_files_have_no_forbidden_content():
    files = _tracked_app_text_files()
    assert files
    problems = []
    for path in files:
        text = path.read_text(encoding="utf-8", errors="ignore").lower()
        for s in FORBIDDEN_SUBSTRINGS:
            if s.lower() in text:
                problems.append(f"{path.relative_to(ROOT)}: {s!r}")
        for w in FORBIDDEN_WORDS:
            if re.search(rf"\b{re.escape(w)}\b", text):
                problems.append(f"{path.relative_to(ROOT)}: {w!r}")
        # "autonomous" is only allowed as "never autonomous"
        if re.search(r"(?<!never )autonomous", text):
            problems.append(f"{path.relative_to(ROOT)}: 'autonomous'")
    assert problems == [], "\n".join(problems)


@pytest.mark.parametrize("page", PAGES, ids=lambda p: p.name)
def test_every_page_applies_theme(page: Path):
    src = page.read_text(encoding="utf-8")
    assert re.search(r"^from app\.lib import theme\b", src, re.MULTILINE), f"{page.name} does not import theme"
    assert re.search(r"\btheme\.apply\(", src), f"{page.name} does not call theme.apply()"
    # apply() must come right after set_page_config, before any other output
    assert src.index("theme.apply(") > src.index("st.set_page_config(")


def test_name_expansion_and_namesake():
    from app.lib import theme

    assert theme.EXPANSION
    assert theme.BIRD
    assert "Health-Integrated Knowledge for Readiness Advisory" in (ROOT / "README.md").read_text(encoding="utf-8")


def test_fonts_are_bundled_with_licences():
    fonts = APP / "assets" / "fonts"
    assert list(fonts.glob("inter-latin-*-normal.woff2"))
    assert list(fonts.glob("jetbrains-mono-latin-*-normal.woff2"))
    for lic in ("Inter-OFL.txt", "JetBrainsMono-OFL.txt"):
        assert "SIL OPEN FONT LICENSE Version 1.1" in (fonts / lic).read_text(encoding="utf-8")
